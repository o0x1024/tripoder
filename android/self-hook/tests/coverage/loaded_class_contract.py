#!/usr/bin/env python3
"""Create/check complete-body contract from the fixed measured ART ELF."""
import argparse
import hashlib
import json
from pathlib import Path
from entry_writer_audit import Elf

ROOT = Path(__file__).resolve().parents[4]
BODIES = {
    'visit': (0x42390c, 0x224), 'internal': (0x4264d4, 0x4ac),
    'loader_visit': (0x6a63e0, 0x448), 'loader_filter': (0x8646fc, 0x98),
    'scope_roots': (0x9de6ac, 0x150),
}


def generate(art):
    data = art.read_bytes()
    expected = json.loads((ROOT / 'android/self-hook-probe/platform.json').read_text())['binaries']['/apex/com.android.art/lib64/libart.so']
    if hashlib.sha256(data).hexdigest() != expected:
        raise ValueError('LOADED_CLASS_ART_IDENTITY')
    elf = Elf(data)
    text = ['/* Fixed measured API37 ELF; generated by loaded_class_contract.py. */',
            '#ifndef TP_LOADED_CLASS_CONTRACT_H', '#define TP_LOADED_CLASS_CONTRACT_H', '#include <stdint.h>']
    records = []
    for name, (rva, size) in BODIES.items():
        body = elf.code(rva, size)
        text.append(f'#define TP_LOADED_{name.upper()}_RVA UINT64_C(0x{rva:x})')
        text.append(f'static const uint8_t tp_loaded_{name}_bytes[] = {{')
        text.extend('    ' + ','.join(f'0x{b:02x}' for b in body[i:i+16]) + ',' for i in range(0, size, 16))
        text.append('};')
        records.append({'name': name, 'rva': hex(rva), 'size': size, 'sha256': hashlib.sha256(body).hexdigest()})
    text.append('#endif')
    return '\n'.join(text) + '\n', {'artSha256': expected, 'bodies': records}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--art', type=Path, required=True)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    header = ROOT / 'android/self-hook/native/coverage/loaded_class_contract.h'
    content, receipt = generate(args.art)
    if args.write:
        header.write_text(content)
    elif header.read_text() != content:
        raise ValueError('LOADED_CLASS_CONTRACT_MISMATCH')
    print(json.dumps(receipt))

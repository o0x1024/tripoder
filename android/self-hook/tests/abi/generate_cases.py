#!/usr/bin/env python3
"""Owned typed C calls used as the independent LLVM ABI oracle. No executable memory writes."""
from pathlib import Path
import argparse
import struct

root = Path(__file__).resolve().parents[4]
destination = root / "android/self-hook-probe/abi-fixtures/native/scalar_cases.c"
types = {"i32": ("int32_t", "TP_SCALAR_I32"), "u32": ("uint32_t", "TP_SCALAR_U32"), "i64": ("int64_t", "TP_SCALAR_I64"), "u64": ("uint64_t", "TP_SCALAR_U64"), "f32": ("float", "TP_SCALAR_F32"), "f64": ("double", "TP_SCALAR_F64"), "void": ("void", "TP_SCALAR_VOID")}
integers = [-2147483648, -1, 0, 1, 17, -31, 2147483647, -7, 12345, -12345, 99, -99, 4, 5, 6, 7]
unsigned = [0xffffffff, 0x80000000, 0, 1, 17, 31, 0x7fffffff, 7, 12345, 0xfedcba98, 99, 100, 4, 5, 6, 7]
wide = [-2**63, -1, 0, 1, 9007199254740993, -9007199254740993, 2**63-1, -7, 12345, -12345, 99, -99, 4, 5, 6, 7]
uwide = [2**64-1, 2**63, 0, 1, 9007199254740993, 0xfedcba9876543210, 2**63-1, 7, 12345, 12346, 99, 100, 4, 5, 6, 7]
floats = [-0.0, 1.25, 2.5, 3.75, 4.5, 5.25, 6.5, 7.75, 8.5, 9.25, 10.5, 11.75, 12.5, 13.25, 14.5, 15.75]
doubles = [-0.0, 1.25, 2.5, 3.75, 4.5, 5.25, 6.5, 7.75, 8.5, 9.25, 10.5, 11.75, 12.5, 13.25, float.fromhex("0x1p-1074"), float.fromhex("0x1.fffffffffffffp+1023")]
cases = [(f"{kind}_16", [(kind, value) for value in values], kind, result) for kind, values, result in [
    ("i32", integers, -2**31), ("u32", unsigned, 2**32-1), ("i64", wide, -2**63), ("u64", uwide, 2**64-1), ("f32", floats, -0.0), ("f64", doubles, doubles[-1])]]
cases += [("mixed_gpr", [(kind, values[i]) for i in range(6) for kind, values in [("u64", uwide), ("f64", doubles)]] + [("u64", uwide[i]) for i in range(6, 10)], "f64", 1.25),
          ("mixed_fpr", [(kind, values[i]) for i in range(6) for kind, values in [("i64", wide), ("f32", floats)]] + [("f32", floats[i]) for i in range(6, 10)], "u64", 2**64-1),
          ("i32_9", [("i32", value) for value in integers[:9]], "i32", -1), ("f32_9", [("f32", value) for value in floats[:9]], "f32", 1.25),
          ("void_0", [], "void", 0)]
cases += [("f32_payload_9",[("f32",("bits",0x7fc01234))]+[("f32",x) for x in floats[1:8]]+[("f32",("bits",0xff800000))],"f32",("bits",0xffc0bcde)),
          ("f64_payload_9",[("f64",("bits",0x7ff800000000cafe))]+[("f64",x) for x in doubles[1:8]]+[("f64",("bits",0xfff0000000000000))],"f64",("bits",0xfff800000000bcde))]

def bits(kind, value):
    if isinstance(value,tuple): return value[1]
    if kind == "f32": return struct.unpack("<I", struct.pack("<f", value))[0]
    if kind == "f64": return struct.unpack("<Q", struct.pack("<d", value))[0]
    return value & ((1 << (32 if kind in ("i32", "u32") else 64))-1)

def literal(kind, value):
    if isinstance(value,tuple): return f'tp_raw_{kind}(UINT'+('32' if kind=='f32' else '64')+f'_C(0x{value[1]:x}))'
    if kind in ("f32", "f64"): return value.hex() + ("f" if kind == "f32" else "")
    if kind == "i64" and value == -2**63: return "INT64_MIN"
    return {"i32": "INT32_C", "u32": "UINT32_C", "i64": "INT64_C", "u64": "UINT64_C"}[kind] + f"({value})"

lines = ['/* Generated by self-hook/tests/abi/generate_cases.py. Typed compiler oracle, not an ABI planner. */', '#include "scalar_cases.h"', '#include <string.h>', '#include <limits.h>',
         'static float tp_raw_f32(uint32_t bits){float value;memcpy(&value,&bits,4);return value;}',
         'static double tp_raw_f64(uint64_t bits){double value;memcpy(&value,&bits,8);return value;}', '']
for name, arguments, result, _ in cases:
    ret = types[result][0]
    signature = ",".join(types[kind][0] for kind, _ in arguments) or "void"
    lines.append(f'extern {ret} oracle_{name}({signature}) __asm__("tp_scalar_capture_entry") __attribute__((visibility("hidden")));')
    lines.append(f'__attribute__((noinline)) static void compiler_{name}(struct tp_scalar_return *out){{')
    call = f'oracle_{name}(' + ",".join(literal(kind, value) for kind, value in arguments) + ')'
    if result == "void": lines.append(f'    {call};out->gpr=0;out->fpr=0;')
    else:
        storage = "uint32_t" if result in ("i32", "u32", "f32") else "uint64_t"
        bank = "fpr" if result.startswith("f") else "gpr"
        other = "gpr" if bank == "fpr" else "fpr"
        lines.append(f'    {ret} value={call};{storage} raw;memcpy(&raw,&value,sizeof(raw));out->{bank}=raw;out->{other}=0;')
    lines.append('}')
    lines.append(f'__attribute__((noinline)) static void compiler_entry_{name}(void (*entry)(void),struct tp_scalar_return *out){{')
    lines.append(f'    typedef {ret} (*typed)({signature});')
    call = '((typed)entry)(' + ",".join(literal(kind, value) for kind, value in arguments) + ')'
    if result == "void": lines.append(f'    {call};out->gpr=0;out->fpr=0;')
    else:
        lines.append(f'    {ret} value={call};{storage} raw;memcpy(&raw,&value,sizeof(raw));out->{bank}=raw;out->{other}=0;')
    lines.append('}')
lines.append('static const struct tp_scalar_fixture_case cases[]={')
for name, arguments, result, value in cases:
    args = ",".join(types[kind][1] for kind, _ in arguments) or "0"
    values = ",".join(f'{{.type={types[kind][1]},.bits=UINT64_C(0x{bits(kind, val):x})}}' for kind, val in arguments) or "{0}"
    lines.append(f'    {{.name="{name}",.signature={{.flags=0,.count={len(arguments)},.result={types[result][1]},.arguments={{{args}}}}},.values={{{values}}},.return_bits=UINT64_C(0x{bits(result, value):x}),.compiler_call=compiler_{name},.compiler_entry=compiler_entry_{name}}},')
lines += ['};', 'const struct tp_scalar_fixture_case *tp_scalar_fixture_cases(size_t *count){*count=sizeof(cases)/sizeof(cases[0]);return cases;}', '']
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
text="\n".join(lines)
if args.check:
    if destination.read_text()!=text: raise RuntimeError('SCALAR_TYPED_ORACLE_OUTDATED')
else:
    destination.parent.mkdir(parents=True, exist_ok=True);destination.write_text(text)
print(destination)
